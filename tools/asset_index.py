# Builds public/js/asset-index.js: for each embedded-data chunk (public/assets/data, in load order) its size in bytes and a
# human label of what it mostly contains, used by the loading-screen progress bar. Labels come from the asset kinds in
# public/assets/manifest.json plus the key each asset sits under in the game script (s_* = weapon sounds, pet_* = pets, ...).
# Run from the repo root after the data chunks change:  python3 tools/asset_index.py
import json,re,os,collections
m=json.load(open('public/assets/manifest.json'))
kind={d['id']:d['kind'] for d in m['data']}; size={d['id']:d['chars'] for d in m['data']}
code=''.join(open(p,encoding='utf-8').read() for p in json.load(open('src/game/manifest.json'))['parts'])
NICE={"heaven":"Heaven Garden","nuketown":"Nuketown","paradise":"Paradise Resort","pool":"Pool Party","forts":"Sniper Forts","antslife":"Ant's Life","xmasdinner":"Christmas Dinner","icepalace":"Ice Palace","farm":"Farm","castle":"Two Castles","coliseum":"Coliseum","mine":"Mine","candyland":"Candy Land","alienplanet":"Alien Planet","whitehouse":"White House","xmastown":"Christmas Town","toyfactory":"Toy Factory","lunapark":"Luna Park","ships":"Pirate Ships","northpole":"North Pole","loveisland":"Love Island","spacestation":"Space Station","ghosttown":"Ghost Town"}  # names as on the loading screen
cat={}
for mm in re.finditer(r'__ASG\[(\d+)\]',code):
    n=int(mm.group(1))
    if n in cat: continue
    pre=code[max(0,mm.start()-400):mm.start()]; post=code[mm.end():mm.end()+400]
    keys=re.findall(r'"([A-Za-z0-9_ .\-]+)":\s*[\[{]?\s*(?:"[^"]*",\s*)?$',pre) or re.findall(r'"([A-Za-z0-9_ .\-]+)":',pre)
    k=(keys[-1] if keys else '').lower(); outer=' '.join(re.findall(r'"([A-Za-z0-9_\-]+)":\{',pre)[-2:]).lower()
    kd=kind.get(n,'')
    own=re.findall(r'"([A-Za-z0-9_\-]+)":\{"p":',code[max(0,mm.start()-60000):mm.start()])
    own=(own[-1] if own else '').lower()
    if kd.startswith('audio'): c='weapon sounds' if k.startswith('s_') else 'music and sound effects'
    elif kd.startswith('font'): c='fonts'
    elif own.endswith('_map') and not kd.startswith('audio'): c='maps:'+NICE.get(own[:-4],own[:-4].replace('_',' ').title())
    elif 'zomb' in k or 'zomb' in outer or k.startswith('zm'): c='zombie models'
    elif k.startswith('pet') or 'pet_' in outer: c='pet models'
    elif k.startswith('pg_') or 'skin' in k or 'skin' in outer: c='character skins'
    elif '"by":' in post[:300] or '"by":' in pre[-120:]: c='weapon models'
    elif kd.startswith('image') and (k.endswith('.png') or k.endswith('.jpg')): c='map textures'
    elif kd.startswith('image'): c='textures and icons'
    else: c='3D models'
    cat[n]=c
html=open('src/index.template.html',encoding='utf-8').read()
files=re.findall(r'<script src="(assets/data/[^"]+)"></script>',html)
out=[]
for f in files:
    ids=[int(x) for x in re.findall(r'__ASG\[(\d+)\]\+?=',open('public/'+f,encoding='utf-8').read())]
    by=collections.Counter()
    for i in set(ids): by[cat.get(i,'game data')]+=size.get(i,0)
    maps=collections.Counter()
    for c in list(by):
        if c.startswith('maps:'): maps[c[5:]]+=by[c]; by['maps']+=by.pop(c)
    top=[c for c,_ in by.most_common(2) if by[c]>0.25*sum(by.values())]
    lab=' and '.join(('maps ('+', '.join(x for x,_ in maps.most_common(3))+')') if c=='maps' else c for c in top) or 'game data'
    out.append([f,os.path.getsize('public/'+f),lab])
js='/* Ashgrove: Undead Siege by Evan - loading-screen index of the embedded-data chunks: [file, bytes, what it mostly holds].\n   Generated by tools/asset_index.py from assets/manifest.json; do not edit by hand. */\nwindow.__ASGIDX='+json.dumps(out,separators=(',',':'))+';\n'
open('public/js/asset-index.js','w').write(js)
for r in out: print(r[0][12:20],round(r[1]/1e6,2),r[2])
print(len(js),'bytes')
